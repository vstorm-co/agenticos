/**
 * Fetch each knowledge-base connector's brand favicon and write them to
 * `src/lib/connector-logos.generated.ts` as base64 data URIs.
 *
 * The same baked marks the MCP cards draw (`gen-mcp-logos.ts`): in colour, on a
 * white tile, compiled in so nothing is fetched while a page renders. A grey
 * glyph in a grey circle read as one icon repeated down the connector list.
 * Run with: bun run gen:connector-logos
 */
import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { faviconUrl, fetchAsDataUri } from "./favicon";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "src", "lib", "connector-logos.generated.ts");

/**
 * Where each connector type's mark comes from - the connectors are the
 * backend's (`app/services/rag/connectors/`). A favicon where the brand serves
 * one large enough; the brand's own published icon where it does not, because
 * Google Drive's favicon is 20 pixels and Git's 32, both blurred on a 2x screen.
 * A plain Git repository wears Git's own mark, not GitHub's: the connector
 * clones from any host. The website connector has no brand and is drawn as a
 * globe.
 */
const SOURCES: Readonly<Record<string, string>> = {
  gdrive: "https://ssl.gstatic.com/images/branding/product/2x/drive_2020q4_48dp.png",
  git: "https://git-scm.com/images/logos/downloads/Git-Icon-1788C.png",
  s3: faviconUrl("aws.amazon.com"),
  sharepoint: faviconUrl("sharepoint.com"),
};

const logos: Record<string, string> = {};
const failed: string[] = [];
for (const [type, source] of Object.entries(SOURCES)) {
  const uri = await fetchAsDataUri(source);
  if (uri) {
    logos[type] = uri;
    console.log(`  ✓ ${type} (${Math.round(uri.length / 1024)} KB)`);
  } else {
    failed.push(type);
  }
}

const body =
  "// AUTO-GENERATED by scripts/gen-connector-logos.ts — do not edit by hand.\n" +
  "// Brand logos for the knowledge-base connectors, inlined as data URIs.\n" +
  "// Regenerate with: bun run gen:connector-logos\n" +
  "export const CONNECTOR_LOGOS: Record<string, string> = {\n" +
  Object.entries(logos)
    .map(([type, uri]) => `  ${JSON.stringify(type)}: ${JSON.stringify(uri)},`)
    .join("\n") +
  "\n};\n";

await writeFile(OUT, body, "utf8");
execFileSync("bunx", ["prettier", "--write", "--log-level", "warn", OUT], { stdio: "inherit" });
console.log(`\nWrote ${Object.keys(logos).length} logos → ${OUT}`);

if (failed.length > 0) {
  console.error(`\n${failed.length} logo(s) missing: ${failed.join(", ")} — re-run to fix.`);
  process.exit(1);
}
